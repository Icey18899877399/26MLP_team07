import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const origin = process.env.FRONTEND_URL || 'http://127.0.0.1:5173'
try {
  const page = await browser.newPage({ viewport: { width: 1560, height: 1060 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(origin)
  await page.getByRole('heading', { name: '原实验图谱', exact: true }).waitFor()
  assert.equal(await page.locator('.page-tabs').count(), 0, 'duplicate top navigation must be removed')
  assert.equal(await page.locator('.app-topbar').count(), 0, 'desktop top bar must be removed')
  assert.equal(await page.getByRole('navigation', { name: '主导航' }).count(), 1)
  const response = await page.request.get(`${origin}/api/interactive-experiments`)
  assert.equal(response.status(), 200)
  const catalog = await response.json()
  assert.equal(catalog.length, 12)
  for (const item of catalog) {
    await page.goto(`${origin}/experiment?experiment=${item.id}`)
    const panel = page.locator('.interactive-panel')
    await panel.getByRole('button', { name: '开始训练', exact: true }).waitFor()
    assert.equal(await page.getByRole('tabpanel', { name: '历史归档原图' }).locator('.original-figure-card').count(), 6, item.id)
    assert.equal(await panel.locator('.hyperparam-form .el-form-item').count(), Object.keys(item.default_params).length, item.id)
    assert.ok((await panel.innerText()).includes(item.datasets[0].path), item.id)
    console.log(`${item.id}: original six images and editable controls verified`)
  }
  await page.goto(`${origin}/experiment?experiment=knn`)
  const panel = page.locator('.interactive-panel')
  await panel.getByRole('button', { name: '开始训练', exact: true }).waitFor()
  await panel.locator('.hyperparam-form .el-form-item').filter({ hasText: 'n_neighbors' }).getByRole('spinbutton').fill('3')
  const firstResponse = page.waitForResponse(r => r.url().endsWith('/api/interactive-experiments') && r.request().method() === 'POST')
  await panel.getByRole('button', { name: '开始训练', exact: true }).click()
  const first = await (await firstResponse).json()
  assert.equal(first.effective_params.n_neighbors, 3)
  await panel.locator('.interactive-result').waitFor()
  assert.ok(await panel.locator('.chart-card').count() >= 2)
  const archive = page.getByRole('tabpanel', { name: '历史归档原图' })
  const beforeImages = await archive.locator('.original-figure-card img').evaluateAll(images => images.map(image => image.src))
  await panel.locator('.hyperparam-form .el-form-item').filter({ hasText: 'n_neighbors' }).getByRole('spinbutton').fill('11')
  const secondResponse = page.waitForResponse(r => r.url().endsWith('/api/interactive-experiments') && r.request().method() === 'POST')
  await panel.getByRole('button', { name: '开始训练', exact: true }).click()
  const second = await (await secondResponse).json()
  assert.equal(second.effective_params.n_neighbors, 11)
  assert.notEqual(first.run_id, second.run_id)
  assert.notDeepEqual(first.metadata.visualizations, second.metadata.visualizations)
  await panel.locator('.interactive-result').waitFor()
  assert.deepEqual(await archive.locator('.original-figure-card img').evaluateAll(images => images.map(image => image.src)), beforeImages)
  await page.screenshot({ path: '../../reference_frames/dual-mode-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '打开导航', exact: true }).click()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '原始数据目录' }).click()
  await page.getByRole('heading', { name: '原始数据目录', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.deepEqual(errors, [])
  console.log('Two real parameterized fits update dynamic charts without changing originals; mobile sidebar verified.')
} finally { await browser.close() }
